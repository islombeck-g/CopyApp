// MARK: - History

struct ClipItem: Codable {
    var text: String
    var date: Date
}

final class HistoryStore {
    private(set) var items: [ClipItem] = []
    private let limit = 50
    private let fileURL: URL

    init() {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let dir = base.appendingPathComponent("CopyStack", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        fileURL = dir.appendingPathComponent("history.json")
        load()
    }

    func add(_ text: String) {
        items.removeAll { $0.text == text }
        items.insert(ClipItem(text: text, date: Date()), at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
        save()
    }

    func clear() {
        items.removeAll()
        save()
    }

    private func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: fileURL, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: fileURL.path)
    }
}

// MARK: - Pasteboard watcher

final class ClipboardMonitor {
    var onText: ((String) -> Void)?
    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    func start() {
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Call after our own pasteboard write so it is not recorded twice.
    func syncCount() {
        lastCount = NSPasteboard.general.changeCount
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignoredTypes) else { return }
        guard let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        onText?(text)
    }
}

// MARK: - Global hotkey (Cmd + .)

private var hotKeyAction: (() -> Void)?

func registerHotKey(_ action: @escaping () -> Void) -> Bool {
    hotKeyAction = action
    var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
    InstallEventHandler(GetApplicationEventTarget(), { _, _, _ in
        DispatchQueue.main.async { hotKeyAction?() }
        return noErr
    }, 1, &spec, nil, nil)

    var ref: EventHotKeyRef?
    let id = EventHotKeyID(signature: OSType(0x4350_5354), id: 1)
    let status = RegisterEventHotKey(UInt32(kVK_ANSI_Period), UInt32(cmdKey), id, GetApplicationEventTarget(), 0, &ref)
    return status == noErr
}

// MARK: - Picker UI

final class PickerPanel: NSPanel {
    override var canBecomeKey: Bool { true }
    override var canBecomeMain: Bool { false }
}

final class RowView: NSTableCellView {
    let label = NSTextField(labelWithString: "")
    let hint = NSTextField(labelWithString: "")

    override init(frame: NSRect) {
        super.init(frame: frame)
        identifier = NSUserInterfaceItemIdentifier("row")
        label.font = .systemFont(ofSize: 13)
        label.lineBreakMode = .byTruncatingTail
        label.translatesAutoresizingMaskIntoConstraints = false
        hint.font = .monospacedDigitSystemFont(ofSize: 11, weight: .medium)
        hint.alignment = .right
        hint.translatesAutoresizingMaskIntoConstraints = false
        addSubview(label)
        addSubview(hint)
        textField = label
        NSLayoutConstraint.activate([
            label.leadingAnchor.constraint(equalTo: leadingAnchor, constant: 12),
            label.trailingAnchor.constraint(equalTo: hint.leadingAnchor, constant: -8),
            label.centerYAnchor.constraint(equalTo: centerYAnchor),
            hint.trailingAnchor.constraint(equalTo: trailingAnchor, constant: -12),
            hint.centerYAnchor.constraint(equalTo: centerYAnchor),
            hint.widthAnchor.constraint(equalToConstant: 14),
        ])
    }

    required init?(coder: NSCoder) { fatalError() }

    override var backgroundStyle: NSView.BackgroundStyle {
        didSet {
            hint.textColor = backgroundStyle == .emphasized ? .alternateSelectedControlTextColor : .secondaryLabelColor
        }
    }
}

final class ListTable: NSTableView {
    var onPick: ((Int) -> Void)?
    var onCancel: (() -> Void)?
    private var area: NSTrackingArea?

    override func keyDown(with event: NSEvent) {
        switch Int(event.keyCode) {
        case kVK_Return, kVK_ANSI_KeypadEnter:
            if selectedRow >= 0 { onPick?(selectedRow) }
        case kVK_Escape:
            onCancel?()
        default:
            if let c = event.charactersIgnoringModifiers, let n = Int(c), (1...9).contains(n), n <= numberOfRows {
                onPick?(n - 1)
            } else {
                super.keyDown(with: event)
            }
        }
    }

    override func acceptsFirstMouse(for event: NSEvent?) -> Bool { true }

    override func updateTrackingAreas() {
        super.updateTrackingAreas()
        if let area { removeTrackingArea(area) }
        let a = NSTrackingArea(rect: .zero, options: [.mouseMoved, .activeAlways, .inVisibleRect], owner: self, userInfo: nil)
        addTrackingArea(a)
        area = a
    }

    override func mouseMoved(with event: NSEvent) {
        let r = row(at: convert(event.locationInWindow, from: nil))
        if r >= 0, r != selectedRow { selectRowIndexes([r], byExtendingSelection: false) }
    }
}

final class PickerController: NSObject, NSTableViewDataSource, NSTableViewDelegate {
    private let store: HistoryStore
    private let onPick: (String) -> Void
    private let panel: PickerPanel
    private let table = ListTable()
    private let scroll = NSScrollView()
    private let header = NSTextField(labelWithString: "")
    private let empty = NSTextField(labelWithString: "Пусто. Скопируй что-нибудь.")
    private var globalMonitor: Any?
    private var appSwitchObserver: NSObjectProtocol?

    private let width: CGFloat = 400
    private let rowHeight: CGFloat = 30
    private let headerHeight: CGFloat = 30
    private let maxRows = 10

    var isVisible: Bool { panel.isVisible }

    init(store: HistoryStore, onPick: @escaping (String) -> Void) {
        self.store = store
        self.onPick = onPick
        panel = PickerPanel(contentRect: NSRect(x: 0, y: 0, width: width, height: 200),
                            styleMask: [.borderless, .nonactivatingPanel],
                            backing: .buffered, defer: true)
        super.init()
        setup()
    }

    private func setup() {
        panel.level = .popUpMenu
        panel.isOpaque = false
        panel.backgroundColor = .clear
        panel.hasShadow = true
        panel.hidesOnDeactivate = false
        panel.isReleasedWhenClosed = false
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient]
        panel.acceptsMouseMovedEvents = true

        let bg = NSVisualEffectView()
        bg.material = .popover
        bg.state = .active
        bg.blendingMode = .behindWindow
        bg.wantsLayer = true
        bg.layer?.cornerRadius = 12
        bg.layer?.masksToBounds = true
        panel.contentView = bg

        header.font = .systemFont(ofSize: 11, weight: .semibold)
        header.textColor = .secondaryLabelColor
        header.stringValue = "ИСТОРИЯ БУФЕРА   ·   клик / Enter / 1–9   ·   Esc"
        header.lineBreakMode = .byTruncatingTail
        bg.addSubview(header)

        empty.font = .systemFont(ofSize: 13)
        empty.textColor = .secondaryLabelColor
        empty.alignment = .center
        bg.addSubview(empty)

        let column = NSTableColumn(identifier: NSUserInterfaceItemIdentifier("c"))
        column.resizingMask = .autoresizingMask
        table.addTableColumn(column)
        table.headerView = nil
        table.rowHeight = rowHeight
        table.intercellSpacing = .zero
        table.backgroundColor = .clear
        table.style = .plain
        table.selectionHighlightStyle = .regular
        table.dataSource = self
        table.delegate = self
        table.target = self
        table.action = #selector(clicked)
        table.onPick = { [weak self] i in self?.pick(i) }
        table.onCancel = { [weak self] in self?.hide() }

        scroll.documentView = table
        scroll.drawsBackground = false
        scroll.hasVerticalScroller = true
        scroll.autohidesScrollers = true
        bg.addSubview(scroll)
    }

    func show() {
        table.reloadData()
        let rows = min(store.items.count, maxRows)
        let listHeight = CGFloat(max(rows, 1)) * rowHeight + 8
        let height = listHeight + headerHeight
        let bounds = NSRect(x: 0, y: 0, width: width, height: height)

        header.frame = NSRect(x: 12, y: height - headerHeight + 7, width: width - 24, height: 16)
        scroll.frame = NSRect(x: 0, y: 4, width: width, height: listHeight - 4)
        empty.frame = NSRect(x: 0, y: (listHeight - 18) / 2, width: width, height: 18)
        empty.isHidden = !store.items.isEmpty
        scroll.isHidden = store.items.isEmpty

        let mouse = NSEvent.mouseLocation
        let screen = NSScreen.screens.first { $0.frame.contains(mouse) } ?? NSScreen.main
        var origin = NSPoint(x: mouse.x - 20, y: mouse.y - height + 12)
        if let vis = screen?.visibleFrame {
            origin.x = min(max(origin.x, vis.minX + 8), vis.maxX - width - 8)
            origin.y = min(max(origin.y, vis.minY + 8), vis.maxY - height - 8)
        }
        panel.setFrame(NSRect(origin: origin, size: bounds.size), display: true)

        panel.orderFrontRegardless()
        panel.makeKey()
        panel.makeFirstResponder(table)
        if !store.items.isEmpty {
            table.selectRowIndexes([0], byExtendingSelection: false)
            table.scrollRowToVisible(0)
        }

        globalMonitor = NSEvent.addGlobalMonitorForEvents(matching: [.leftMouseDown, .rightMouseDown, .otherMouseDown]) { [weak self] _ in
            self?.hide()
        }
        appSwitchObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] _ in
            self?.hide()
        }
    }

    func hide() {
        panel.orderOut(nil)
        if let m = globalMonitor { NSEvent.removeMonitor(m); globalMonitor = nil }
        if let o = appSwitchObserver { NSWorkspace.shared.notificationCenter.removeObserver(o); appSwitchObserver = nil }
    }

    func toggle() {
        isVisible ? hide() : show()
    }

    @objc private func clicked() {
        let r = table.clickedRow
        if r >= 0 { pick(r) }
    }

    private func pick(_ index: Int) {
        guard store.items.indices.contains(index) else { return }
        let text = store.items[index].text
        hide()
        onPick(text)
    }

    // MARK: table

    func numberOfRows(in tableView: NSTableView) -> Int { store.items.count }

    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        let cell = (tableView.makeView(withIdentifier: NSUserInterfaceItemIdentifier("row"), owner: nil) as? RowView) ?? RowView()
        let text = store.items[row].text
        cell.label.stringValue = Self.preview(text)
        cell.toolTip = String(text.prefix(600))
        cell.hint.stringValue = row < 9 ? "\(row + 1)" : ""
        return cell
    }

    private static func preview(_ text: String) -> String {
        let flat = text.components(separatedBy: .whitespacesAndNewlines).filter { !$0.isEmpty }.joined(separator: " ")
        return String(flat.prefix(200))
    }
}

// MARK: - App

final class AppDelegate: NSObject, NSApplicationDelegate, NSMenuDelegate {
    private let store = HistoryStore()
    private let monitor = ClipboardMonitor()
    private var picker: PickerController!
    private var statusItem: NSStatusItem!

    func applicationDidFinishLaunching(_ notification: Notification) {
        picker = PickerController(store: store) { [weak self] text in self?.paste(text) }

        monitor.onText = { [weak self] text in self?.store.add(text) }
        monitor.start()

        setupStatusItem()

        if !registerHotKey({ [weak self] in self?.picker.toggle() }) {
            let alert = NSAlert()
            alert.messageText = "Не удалось занять ⌘ ."
            alert.informativeText = "Сочетание уже занято другим приложением. Закрой его и перезапусти CopyStack."
            alert.runModal()
        }

        if CommandLine.arguments.contains("--show") {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { self.picker.show() }
        }

        let key = "didAskAccessibility"
        if !AXIsProcessTrusted(), !UserDefaults.standard.bool(forKey: key) {
            UserDefaults.standard.set(true, forKey: key)
            requestAccessibility()
        }
    }

    private func setupStatusItem() {
        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.squareLength)
        statusItem.button?.image = NSImage(systemSymbolName: "doc.on.clipboard", accessibilityDescription: "CopyStack")
        let menu = NSMenu()
        menu.delegate = self
        statusItem.menu = menu
    }

    func menuNeedsUpdate(_ menu: NSMenu) {
        menu.removeAllItems()
        menu.addItem(withTitle: "Показать историю  ⌘ .", action: #selector(showPicker), keyEquivalent: "").target = self
        menu.addItem(withTitle: "Очистить историю", action: #selector(clearHistory), keyEquivalent: "").target = self
        menu.addItem(.separator())

        if !AXIsProcessTrusted() {
            let item = menu.addItem(withTitle: "Включить автовставку…", action: #selector(requestAccessibilityAction), keyEquivalent: "")
            item.target = self
        }
        let login = menu.addItem(withTitle: "Запускать при входе", action: #selector(toggleLogin), keyEquivalent: "")
        login.target = self
        login.state = SMAppService.mainApp.status == .enabled ? .on : .off

        menu.addItem(.separator())
        menu.addItem(withTitle: "Выйти", action: #selector(NSApplication.terminate(_:)), keyEquivalent: "q")
    }

    @objc private func showPicker() {
        // let the menu close before the panel grabs key
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.1) { self.picker.show() }
    }

    @objc private func clearHistory() { store.clear() }

    @objc private func requestAccessibilityAction() { requestAccessibility() }

    @objc private func toggleLogin() {
        let service = SMAppService.mainApp
        do {
            if service.status == .enabled { try service.unregister() } else { try service.register() }
        } catch {
            let alert = NSAlert(error: error)
            alert.runModal()
        }
    }

    private func requestAccessibility() {
        let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(opts)
    }

    /// Put text on the pasteboard, then Cmd+V into the previously focused app if allowed.
    private func paste(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        monitor.syncCount()
        store.add(text)

        guard AXIsProcessTrusted() else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) {
            let src = CGEventSource(stateID: .combinedSessionState)
            let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
            let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
            down?.flags = .maskCommand
            up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
        }
    }
}

let app = NSApplication.shared
let delegate = AppDelegate()
app.delegate = delegate
app.setActivationPolicy(.accessory)
app.run()
